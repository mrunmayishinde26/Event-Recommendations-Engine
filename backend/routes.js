/**
 * routes.js
 * Centralises all Express route definitions for the CleverTap Integration Tool.
 */

const express = require('express');
const router = express.Router();

const { scanWebsite } = require('./scanner');
const { sendEvent, sendBatchEvents } = require('./clevertap');

// ─── POST /api/scan ───────────────────────────────────────────────────────────
/**
 * Scans a given website URL with Puppeteer and returns a list of
 * detected trackable events plus element metadata.
 *
 * Body: { url: string }
 * Response: { url, detectedEvents: Event[], scanSummary: object }
 */
router.post('/scan', async (req, res) => {
  const { url } = req.body;

  if (!url || typeof url !== 'string') {
    return res.status(400).json({ error: 'A valid "url" string is required.' });
  }

  // Normalise URL – prepend https:// if missing
  const normalised = url.startsWith('http') ? url : `https://${url}`;

  try {
    console.log(`[Scanner] Starting scan for: ${normalised}`);
    const result = await scanWebsite(normalised);
    res.json({ success: true, ...result });
  } catch (err) {
    console.error('[Scanner] Error:', err.message);
    res.status(500).json({ error: `Scan failed: ${err.message}` });
  }
});

// ─── POST /api/send-event ─────────────────────────────────────────────────────
/**
 * Forwards a single event to CleverTap's Upload API.
 *
 * Body: {
 *   accountId: string,
 *   passcode:  string,
 *   identity:  string,
 *   eventName: string,
 *   eventData: object
 * }
 */
router.post('/send-event', async (req, res) => {
  const { accountId, passcode, identity, eventName, eventData } = req.body;

  if (!accountId || !passcode || !eventName) {
    return res.status(400).json({
      error: 'accountId, passcode, and eventName are required.',
    });
  }

  try {
    const result = await sendEvent({ accountId, passcode, identity, eventName, eventData });
    res.json({ success: true, result });
  } catch (err) {
    console.error('[CleverTap] Send-event error:', err.message);
    res.status(500).json({ error: err.message });
  }
});

// ─── POST /api/send-batch ─────────────────────────────────────────────────────
/**
 * Forwards multiple events at once (used by tracker.js batching).
 *
 * Body: {
 *   accountId: string,
 *   passcode:  string,
 *   events: Array<{ identity, eventName, eventData }>
 * }
 */
router.post('/send-batch', async (req, res) => {
  const { accountId, passcode, events } = req.body;

  if (!accountId || !passcode || !Array.isArray(events) || events.length === 0) {
    return res.status(400).json({
      error: 'accountId, passcode, and a non-empty events array are required.',
    });
  }

  try {
    const result = await sendBatchEvents({ accountId, passcode, events });
    res.json({ success: true, result });
  } catch (err) {
    console.error('[CleverTap] Send-batch error:', err.message);
    res.status(500).json({ error: err.message });
  }
});

// ─── POST /api/generate-script ────────────────────────────────────────────────
/**
 * Generates the personalised tracker.js snippet based on chosen events
 * and CleverTap credentials.
 *
 * Body: {
 *   accountId:      string,
 *   passcode:       string,
 *   backendUrl:     string,   // e.g. "https://your-backend.com"
 *   selectedEvents: string[]  // event names to track
 * }
 */
router.post('/generate-script', (req, res) => {
  const { accountId, passcode, backendUrl, selectedEvents } = req.body;

  if (!accountId || !passcode || !backendUrl) {
    return res.status(400).json({
      error: 'accountId, passcode, and backendUrl are required.',
    });
  }

  const events = Array.isArray(selectedEvents) ? selectedEvents : [];
  const script = buildTrackerScript({ accountId, passcode, backendUrl, events });

  res.json({ success: true, script });
});

// ─── Helper: build tracker script ─────────────────────────────────────────────
function buildTrackerScript({ accountId, passcode, backendUrl, events }) {
  return `<!-- CleverTap Auto-Tracker – generated by CleverTap Integration Tool -->
<script>
(function () {
  // ── Configuration ────────────────────────────────────────────────────────
  var CT_CONFIG = {
    accountId:     "${accountId}",
    passcode:      "${passcode}",
    backendUrl:    "${backendUrl.replace(/\/$/, '')}",
    trackedEvents: ${JSON.stringify(events)},
    batchSize:     5,
    flushInterval: 5000   // ms
  };

  var _queue = [];
  var _identity = localStorage.getItem("ct_identity") || "anonymous_" + Math.random().toString(36).slice(2);
  localStorage.setItem("ct_identity", _identity);

  // ── Core send function ───────────────────────────────────────────────────
  function sendEvents(batch) {
    if (!batch.length) return;
    var payload = {
      accountId: CT_CONFIG.accountId,
      passcode:  CT_CONFIG.passcode,
      events:    batch
    };
    var xhr = new XMLHttpRequest();
    xhr.open("POST", CT_CONFIG.backendUrl + "/api/send-batch", true);
    xhr.setRequestHeader("Content-Type", "application/json");
    xhr.send(JSON.stringify(payload));
  }

  function track(eventName, properties) {
    if (CT_CONFIG.trackedEvents.length && CT_CONFIG.trackedEvents.indexOf(eventName) === -1) return;
    var evt = {
      identity:  _identity,
      eventName: eventName,
      eventData: Object.assign({
        page_url:   window.location.href,
        page_title: document.title,
        referrer:   document.referrer,
        timestamp:  new Date().toISOString()
      }, properties || {})
    };
    _queue.push(evt);
    console.log("[CT Tracker] Queued:", eventName, evt.eventData);
    if (_queue.length >= CT_CONFIG.batchSize) flush();
  }

  function flush() {
    if (!_queue.length) return;
    var batch = _queue.splice(0, _queue.length);
    sendEvents(batch);
  }

  // Auto-flush on interval and page unload
  setInterval(flush, CT_CONFIG.flushInterval);
  window.addEventListener("beforeunload", flush);

  // ── Page View ────────────────────────────────────────────────────────────
  track("Page Viewed");

  // ── Button / Link Clicks ─────────────────────────────────────────────────
  var CART_SELECTORS     = [".add-to-cart","[data-action='add-to-cart']","button[id*='cart']","button[class*='cart']","[class*='addtocart']"];
  var CHECKOUT_SELECTORS = [".checkout",".proceed-to-checkout","button[id*='checkout']","[class*='checkout']"];
  var BUY_SELECTORS      = [".buy-now","[class*='buynow']","button[id*='buy']"];
  var WISHLIST_SELECTORS = [".add-to-wishlist","[class*='wishlist']"];

  function matches(el, selectors) {
    return selectors.some(function(s) { try { return el.matches(s); } catch(e) { return false; } });
  }

  document.addEventListener("click", function (e) {
    var el = e.target;
    // Walk up max 3 levels to catch clicks on inner spans/icons
    for (var i = 0; i < 3 && el; i++) {
      if (matches(el, CART_SELECTORS))     { track("Added to Cart",        { element_text: el.innerText }); return; }
      if (matches(el, CHECKOUT_SELECTORS)) { track("Checkout Started",     { element_text: el.innerText }); return; }
      if (matches(el, BUY_SELECTORS))      { track("Buy Now Clicked",      { element_text: el.innerText }); return; }
      if (matches(el, WISHLIST_SELECTORS)) { track("Added to Wishlist",    { element_text: el.innerText }); return; }
      el = el.parentElement;
    }
  }, true);

  // ── Form Submissions ─────────────────────────────────────────────────────
  document.addEventListener("submit", function (e) {
    var form = e.target;
    var action = (form.action || "").toLowerCase();
    var id     = (form.id    || "").toLowerCase();
    var cls    = (form.className || "").toLowerCase();

    if (/login|signin|sign-in/.test(action + id + cls))   { track("User Login");    return; }
    if (/signup|register|join/.test(action + id + cls))    { track("User Signup");   return; }
    if (/checkout|payment|order/.test(action + id + cls))  { track("Order Placed");  return; }
    if (/search/.test(action + id + cls))                  { track("Search Performed", { query: (form.querySelector('[name=q],[name=query],[name=search]') || {}).value }); return; }

    track("Form Submitted", { form_id: form.id, form_action: form.action });
  }, true);

  // ── Product Views (URL pattern heuristic) ────────────────────────────────
  var href = window.location.href.toLowerCase();
  if (/\/product\/|\/item\/|\/p\/|\/detail\/|productid=/.test(href)) {
    var productName = document.querySelector("h1,h2,.product-title,.product-name");
    track("Product Viewed", {
      product_name:  productName ? productName.innerText.trim() : "",
      product_url:   window.location.href
    });
  }

  // ── Purchase Confirmation ────────────────────────────────────────────────
  if (/\/order-confirmation|\/thank-you|\/checkout\/success|\/payment\/success/.test(href)) {
    track("Purchase Completed");
  }

  // ── Expose global API for manual tracking ────────────────────────────────
  window.CTTracker = { track: track, flush: flush, setIdentity: function(id) { _identity = id; } };
  console.log("[CT Tracker] Initialised for account:", CT_CONFIG.accountId);
})();
</script>`;
}

module.exports = router;
